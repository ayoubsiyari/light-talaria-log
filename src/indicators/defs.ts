export function getIndicatorDef(id: IndicatorId): IndicatorDef {
  return INDICATOR_DEFS[id];
}

export function formatIndicatorLabel(id: IndicatorId, params: Record<string, number | string | boolean>): string {
  const d = INDICATOR_DEFS[id];
  const parts = d.fields
    .filter((f) => f.type === 'number')
    .slice(0, 3)
    .map((f) => {
      const v = params[f.key] ?? d.defaultParams[f.key];
      return typeof v === 'number' ? (Number.isInteger(v) ? String(v) : v.toFixed(2)) : String(v);
    });
  return parts.length ? `${d.shortLabel} ${parts.join(',')}` : d.shortLabel;
}
