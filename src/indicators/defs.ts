import type { IndicatorDef, IndicatorId, ParamField } from '@/types/indicator';

const period = (defaultPeriod = 14, max = 500): ParamField => {
  void defaultPeriod;
  return {
    key: 'period',
    label: 'Period',
    type: 'number',
    min: 1,
    max,
    step: 1,
  };
};

const numField = (
  key: string,
  label: string,
  defaultValue: number,
  min = 0,
  max = 500,
  step = 1,
): ParamField => {
  void defaultValue;
  return {
    key,
    label,
    type: 'number',
    min,
    max,
    step,
  };
};

function def(
  partial: Omit<IndicatorDef, 'shortLabel'> & { shortLabel?: string },
): IndicatorDef {
  return {
    shortLabel: partial.shortLabel ?? partial.label,
    ...partial,
  };
}

